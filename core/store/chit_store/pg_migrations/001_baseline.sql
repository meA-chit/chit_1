-- Integrity rules that were SQLite triggers --------------------------------------------------------------------------

CREATE FUNCTION chit_household_owner_must_be_adult() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM household_members
                   WHERE id = NEW.owner_member_id AND household_id = NEW.id AND role = 'adult') THEN
        RAISE EXCEPTION 'household owner must be an adult in this household';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER household_owner_must_be_adult
    BEFORE UPDATE OF owner_member_id ON households
    FOR EACH ROW EXECUTE FUNCTION chit_household_owner_must_be_adult();

CREATE FUNCTION chit_household_owner_cannot_be_removed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM households WHERE id = OLD.household_id AND owner_member_id = OLD.id) THEN
        RAISE EXCEPTION 'transfer household ownership before removing the owner';
    END IF;
    RETURN OLD;
END $$;
CREATE TRIGGER household_owner_cannot_be_removed
    BEFORE DELETE ON household_members
    FOR EACH ROW EXECUTE FUNCTION chit_household_owner_cannot_be_removed();

CREATE FUNCTION chit_child_adult_assignment() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM household_members
                   WHERE id = NEW.child_id AND household_id = NEW.household_id AND role = 'child')
       OR NOT EXISTS (SELECT 1 FROM household_members
                      WHERE id = NEW.adult_id AND household_id = NEW.household_id AND role = 'adult') THEN
        RAISE EXCEPTION '% assignment must link a child to an adult in the same household', TG_ARGV[0];
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER child_pickup_assignment_must_be_adult
    BEFORE INSERT ON child_pickup_adults
    FOR EACH ROW EXECUTE FUNCTION chit_child_adult_assignment('pickup');
CREATE TRIGGER child_dropoff_assignment_must_be_adult
    BEFORE INSERT ON child_dropoff_adults
    FOR EACH ROW EXECUTE FUNCTION chit_child_adult_assignment('drop-off');
