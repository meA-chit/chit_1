-- Postgres baseline (ADR-0015, docs/core/postgres-port-audit.md). Consolidates the end state of the SQLite
-- migrations 001..020 in ../migrations; the SQLite store stays as a standby and is not changed by this file.
--
-- Differences from the SQLite schema, all deliberate:
--   * every tenant table carries household_id, tied to its parent by a composite foreign key, so a row can never
--     point at a parent in another household and row-level security stays a one-column policy;
--   * `seq` (identity) replaces SQLite's implicit rowid wherever the code orders by rowid;
--   * COLLATE NOCASE becomes a lower() index; triggers are PL/pgSQL; REAL is DOUBLE PRECISION;
--   * planner_skips is keyed by household_id too.
-- Dates stay ISO TEXT and flags stay INTEGER 0/1 so API output does not change.

CREATE TABLE households (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    timezone TEXT NOT NULL,
    country_code TEXT,
    region TEXT,
    owner_member_id TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    modules_configured INTEGER NOT NULL DEFAULT 0 CHECK (modules_configured IN (0, 1)),
    latitude DOUBLE PRECISION CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    household_type TEXT NOT NULL DEFAULT 'family'
);

CREATE TABLE household_members (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id TEXT PRIMARY KEY,
    household_id TEXT NOT NULL REFERENCES households(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('adult', 'child', 'helper')),
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    birth_date TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    modules_restricted INTEGER NOT NULL DEFAULT 0 CHECK (modules_restricted IN (0, 1)),
    avatar TEXT,
    color TEXT,
    UNIQUE (id, household_id)
);
CREATE INDEX household_members_by_household ON household_members(household_id, role, name);

-- The owner must belong to the household; checked at commit so a household and its first member can be inserted together.
